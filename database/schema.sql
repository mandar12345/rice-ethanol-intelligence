-- Rice Ethanol Intelligence POC: Supabase multi-tenant foundation.
-- Run in Supabase SQL Editor. Create users in Authentication first, then insert user_profiles.
BEGIN;
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS organizations (
  organization_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS plants (
  plant_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id UUID NOT NULL REFERENCES organizations(organization_id) ON DELETE CASCADE,
  plant_name TEXT NOT NULL,
  capacity_klpd NUMERIC(12,3) NOT NULL CHECK (capacity_klpd > 0),
  timezone TEXT NOT NULL DEFAULT 'Asia/Kolkata',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (organization_id, plant_name)
);
CREATE TABLE IF NOT EXISTS user_profiles (
  user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  organization_id UUID NOT NULL REFERENCES organizations(organization_id) ON DELETE CASCADE,
  plant_id UUID REFERENCES plants(plant_id) ON DELETE SET NULL,
  display_name TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin','management','production','accounts')),
  is_active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION public.current_org_id()
RETURNS UUID LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$ SELECT organization_id FROM public.user_profiles WHERE user_id = auth.uid() AND is_active = true LIMIT 1 $$;
CREATE OR REPLACE FUNCTION public.current_plant_id()
RETURNS UUID LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$ SELECT plant_id FROM public.user_profiles WHERE user_id = auth.uid() AND is_active = true LIMIT 1 $$;
CREATE OR REPLACE FUNCTION public.current_user_role()
RETURNS TEXT LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
AS $$ SELECT role FROM public.user_profiles WHERE user_id = auth.uid() AND is_active = true LIMIT 1 $$;

CREATE TABLE IF NOT EXISTS daily_production (
  production_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id UUID NOT NULL REFERENCES organizations(organization_id) ON DELETE CASCADE,
  plant_id UUID NOT NULL REFERENCES plants(plant_id) ON DELETE CASCADE,
  operating_date DATE NOT NULL,
  process_mode TEXT NOT NULL CHECK (process_mode IN ('batch','continuous','hybrid')),
  capacity_klpd NUMERIC(12,3) NOT NULL,
  target_kl NUMERIC(12,3) NOT NULL DEFAULT 0,
  ethanol_kl NUMERIC(12,3) NOT NULL DEFAULT 0,
  rice_mt NUMERIC(14,3) NOT NULL DEFAULT 0,
  maize_mt NUMERIC(14,3) NOT NULL DEFAULT 0,
  ddgs_mt NUMERIC(14,3) NOT NULL DEFAULT 0,
  co2_mt NUMERIC(14,3) NOT NULL DEFAULT 0,
  electricity_kwh NUMERIC(16,3) NOT NULL DEFAULT 0,
  steam_mt NUMERIC(14,3) NOT NULL DEFAULT 0,
  water_m3 NUMERIC(14,3) NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (plant_id, operating_date)
);
CREATE TABLE IF NOT EXISTS daily_inventory (
  inventory_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id UUID NOT NULL REFERENCES organizations(organization_id) ON DELETE CASCADE,
  plant_id UUID NOT NULL REFERENCES plants(plant_id) ON DELETE CASCADE,
  operating_date DATE NOT NULL,
  material TEXT NOT NULL,
  uom TEXT NOT NULL,
  receipt_qty NUMERIC(16,3) NOT NULL DEFAULT 0,
  consumption_qty NUMERIC(16,3) NOT NULL DEFAULT 0,
  closing_qty NUMERIC(16,3) NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (plant_id, operating_date, material)
);
CREATE TABLE IF NOT EXISTS daily_finance (
  finance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id UUID NOT NULL REFERENCES organizations(organization_id) ON DELETE CASCADE,
  plant_id UUID NOT NULL REFERENCES plants(plant_id) ON DELETE CASCADE,
  entry_date DATE NOT NULL,
  category TEXT NOT NULL CHECK (category IN ('ethanol_sales','byproduct_sales','feedstock_cost','utilities_cost','labor_cost','maintenance_cost','other_cost')),
  amount_inr NUMERIC(18,2) NOT NULL CHECK (amount_inr >= 0),
  source_system TEXT NOT NULL DEFAULT 'manual',
  external_reference TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (plant_id, entry_date, category, source_system, external_reference)
);
CREATE TABLE IF NOT EXISTS audit_logs (
  audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id UUID NOT NULL REFERENCES organizations(organization_id) ON DELETE CASCADE,
  plant_id UUID REFERENCES plants(plant_id) ON DELETE SET NULL,
  actor_user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  action TEXT NOT NULL,
  entity_name TEXT NOT NULL,
  entity_id TEXT,
  details JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_daily_prod_org_plant_date ON daily_production(organization_id, plant_id, operating_date);
CREATE INDEX IF NOT EXISTS idx_daily_inv_org_plant_date ON daily_inventory(organization_id, plant_id, operating_date);
CREATE INDEX IF NOT EXISTS idx_daily_fin_org_plant_date ON daily_finance(organization_id, plant_id, entry_date);

ALTER TABLE organizations ENABLE ROW LEVEL SECURITY;
ALTER TABLE plants ENABLE ROW LEVEL SECURITY;
ALTER TABLE user_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE daily_production ENABLE ROW LEVEL SECURITY;
ALTER TABLE daily_inventory ENABLE ROW LEVEL SECURITY;
ALTER TABLE daily_finance ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit_logs ENABLE ROW LEVEL SECURITY;

-- Authenticated users can read only their own profile. Provision profiles as an admin via SQL Editor.
DROP POLICY IF EXISTS profile_read_self ON user_profiles;
CREATE POLICY profile_read_self ON user_profiles FOR SELECT TO authenticated USING (user_id = auth.uid());
DROP POLICY IF EXISTS org_read_member ON organizations;
CREATE POLICY org_read_member ON organizations FOR SELECT TO authenticated USING (organization_id = public.current_org_id());
DROP POLICY IF EXISTS plant_read_member ON plants;
CREATE POLICY plant_read_member ON plants FOR SELECT TO authenticated USING (organization_id = public.current_org_id());

DROP POLICY IF EXISTS production_read_role ON daily_production;
CREATE POLICY production_read_role ON daily_production FOR SELECT TO authenticated
USING (organization_id = public.current_org_id() AND (public.current_user_role() IN ('admin','management','production')) AND (public.current_user_role() IN ('admin','management') OR (public.current_plant_id() IS NOT NULL AND plant_id = public.current_plant_id())));
DROP POLICY IF EXISTS inventory_read_role ON daily_inventory;
CREATE POLICY inventory_read_role ON daily_inventory FOR SELECT TO authenticated
USING (organization_id = public.current_org_id() AND (public.current_user_role() IN ('admin','management','production')) AND (public.current_user_role() IN ('admin','management') OR (public.current_plant_id() IS NOT NULL AND plant_id = public.current_plant_id())));
DROP POLICY IF EXISTS finance_read_role ON daily_finance;
CREATE POLICY finance_read_role ON daily_finance FOR SELECT TO authenticated
USING (organization_id = public.current_org_id() AND (public.current_user_role() IN ('admin','management','accounts')) AND (public.current_user_role() IN ('admin','management') OR (public.current_plant_id() IS NOT NULL AND plant_id = public.current_plant_id())));
DROP POLICY IF EXISTS audit_read_admin_management ON audit_logs;
CREATE POLICY audit_read_admin_management ON audit_logs FOR SELECT TO authenticated
USING (organization_id = public.current_org_id() AND public.current_user_role() IN ('admin','management'));

-- This POC schema intentionally grants read access only. Add narrowly scoped INSERT/UPDATE policies
-- after the actual data-entry workflows and approval rules have been agreed.
GRANT USAGE ON SCHEMA public TO authenticated;
GRANT SELECT ON organizations, plants, user_profiles, daily_production, daily_inventory, daily_finance, audit_logs TO authenticated;
COMMIT;
